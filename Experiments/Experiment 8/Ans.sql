
create table Employee (
EMP_ID INT PRIMARY KEY,
EMP_NAME VARCHAR(20),
SALARY NUMERIC,
DEPARTMENT_NAME VARCHAR(20)
);

CREATE OR REPLACE PROCEDURE	Insert_Employee(P_EMP_ID INT,P_EMP_NAME VARCHAR(20),P_SALARY NUMERIC,P_DEPARTMENT_NAME VARCHAR(20))
AS $$
BEGIN 
  IF
   P_EMP_ID % 2 != 0 THEN
   INSERT INTO EMPLOYEE VALUES(P_EMP_ID,P_EMP_NAME,P_SALARY,P_DEPARTMENT_NAME);
   RAISE NOTICE 'Employee inserted successfully.';
  ELSE
   RAISE EXCEPTION 'EMPLOYEE CAN NOT INSERT ONLY ODD EMP_ID IS ALLOWED TO INSERT';
  END IF;

END;
$$ LANGUAGE PLPGSQL



